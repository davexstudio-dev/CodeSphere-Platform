import { oc } from "@orpc/contract";
import * as z from "zod";

/**
 * Message of the FORBIDDEN a suspended Member gets on any write (#123). oRPC maps a custom
 * code to HTTP 500, so the refusal stays a standard FORBIDDEN and this message tells it apart.
 */
export const MEMBER_SUSPENDED_MESSAGE = "MEMBER_SUSPENDED";

/** True for the refusal a suspended Member gets, as opposed to a plain « not an Admin ». */
export function isMemberSuspended(error: unknown): boolean {
	const { code, message } = (error ?? {}) as {
		code?: unknown;
		message?: unknown;
	};
	return code === "FORBIDDEN" && message === MEMBER_SUSPENDED_MESSAGE;
}

/** Identifier of a persisted entity (UUID v7 generated by Postgres). */
export const Id = z.uuid();

/** ISO 8601 timestamp. */
export const Timestamp = z.iso.datetime();

/** Declared language of a piece of content. */
export const Language = z.enum(["fr", "en"]);

/** Country (ISO 3166-1 alpha-2, or "OTHER" for the diaspora) and optional city. */
export const Region = z.object({
	country: z.union([z.string().length(2).toUpperCase(), z.literal("OTHER")]),
	city: z.string().max(100).optional(),
});

/** Client-generated key that makes a create call safe to retry (offline outbox). */
export const IdempotencyKey = z.uuid();

/** Version of the entity the client last saw; a mismatch yields CONFLICT. */
export const ExpectedVersion = z.number().int().min(1);

/** Markdown body with a bounded size. */
export const Markdown = z.string().min(1).max(20_000);

export const PageInput = z.object({
	cursor: z.string().optional(),
	limit: z.number().int().min(1).max(50).default(20),
});

/** Cursor-paginated envelope: the cursor is opaque and issued by the server. */
export const Page = <T extends z.ZodType>(item: T) =>
	z.object({
		items: z.array(item),
		nextCursor: z.string().nullable(),
	});

/** Moderation and editing powers unlocked by Reputation (decision #219, glossary: Privilege). */
export const PRIVILEGES = [
	"flag",
	"propose_tag_edit",
	"downvote",
	"close_vote",
	"edit_tags",
	"submit_feed_item",
] as const;
export const PrivilegeName = z.enum(PRIVILEGES);
export type PrivilegeName = z.infer<typeof PrivilegeName>;

/** Refusal of a Privilege the Member has not earned yet: says what is needed and what they have. */
export const PrivilegeRequired = {
	data: z.object({
		privilege: PrivilegeName,
		required: z.number().int(),
		current: z.number().int(),
	}),
};

/**
 * Base builder for every contract. Standard codes (UNAUTHORIZED, FORBIDDEN,
 * NOT_FOUND, CONFLICT) need no schema; only errors that carry data are typed.
 * oRPC fills BAD_REQUEST's `issues` itself when an input fails validation (#59).
 */
export const base = oc.errors({
	BAD_REQUEST: {
		data: z.object({
			issues: z.array(
				z.object({
					path: z.array(z.union([z.string(), z.number()])),
					message: z.string(),
				}),
			),
		}),
	},
	INTERNAL_SERVER_ERROR: {
		data: z.object({ requestId: z.string(), traceId: z.string().optional() }),
	},
	TOO_MANY_REQUESTS: {
		data: z.object({ retryAfter: z.number() }),
	},
	// No database for this deployment, or the database is down: the request can be retried later.
	SERVICE_UNAVAILABLE: {},
});
